"""Shared building blocks for every database model."""
import enum
import uuid
from datetime import datetime

from sqlalchemy import DateTime, Enum, MetaData, func, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Predictable constraint names, e.g. "fk_messages_conversation_id_conversations".
# Alembic needs stable names to be able to change or drop constraints later.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UUIDPrimaryKeyMixin:
    """UUID primary key. Hard to guess, unlike 1, 2, 3, so it is safer in URLs."""
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,                        # generated by Python...
        server_default=text("gen_random_uuid()"),  # ...or by Postgres for raw SQL inserts
    )


class TimestampMixin:
    """created_at / updated_at, filled in automatically by the database."""
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )


def str_enum(enum_cls: type[enum.Enum], name: str) -> Enum:
    """Store a Python enum as VARCHAR + CHECK constraint.

    Adding a new value later = a simple migration (native PG ENUM types are harder to change).
    """
    return Enum(
        enum_cls,
        name=name,
        native_enum=False,
        create_constraint=True,
        length=32,
        values_callable=lambda e: [m.value for m in e],  # store "hot", not "HOT"
        validate_strings=True,
    )
